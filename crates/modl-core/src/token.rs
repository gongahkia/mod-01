use serde::{Deserialize, Serialize};

use crate::span::Span;

/// MODL/1 lexical token. Literal values are decoded but every token retains its source span.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(tag = "kind", content = "value")]
pub enum TokenKind {
    Identifier(String),
    Asset(String),
    Int(i64),
    Num(f64),
    Text(String),
    Frames(u32),
    Seconds(f64),
    Comment(String),
    Import,
    As,
    Pub,
    Private,
    Const,
    State,
    Let,
    Var,
    Fn,
    Task,
    On,
    Start,
    Update,
    Draw,
    Raster,
    Record,
    Enum,
    Match,
    Case,
    If,
    Elif,
    Else,
    For,
    In,
    While,
    Return,
    Break,
    Continue,
    Wait,
    True,
    False,
    None,
    And,
    Or,
    Not,
    Assert,
    Newline,
    Indent,
    Dedent,
    LeftParen,
    RightParen,
    LeftBracket,
    RightBracket,
    Colon,
    Comma,
    Dot,
    Arrow,
    Range,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Ampersand,
    Pipe,
    Caret,
    Tilde,
    ShiftLeft,
    ShiftRight,
    ShiftRightUnsigned,
    Equal,
    EqualEqual,
    BangEqual,
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    Eof,
}

